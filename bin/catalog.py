#!/usr/bin/env python3
"""Generate or verify CATALOG.md for the skill pack. Stdlib only.

    bin/catalog.py            # write CATALOG.md
    bin/catalog.py --check    # exit 1 if CATALOG.md is stale
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
DESC = re.compile(r"^description:\s*(.+)$", re.M)
NAME = re.compile(r"^name:\s*(\S+)$", re.M)

GROUPS = {
    "web-dev": "Web development",
    "web-design": "Web design",
    "ui-ux": "UI/UX & accessibility",
    "mobile-dev": "Mobile development",
    "mobile-design": "Mobile design",
    "ml": "Machine learning & LLM",
    "samp": "SA-MP / open.mp",
    "samp-client": "SA-MP client (C++)",
    "ops": "Ops & delivery",
    "productivity": "Product & documents",
    "meta": "Meta: maintaining the pack",
}


def read(p: pathlib.Path) -> tuple[str, str, str]:
    text = p.read_text(encoding="utf-8", errors="replace")
    m = FRONT.match(text)
    fm = m.group(1) if m else ""
    name = (NAME.search(fm).group(1).strip().strip('"') if NAME.search(fm) else p.parent.name)
    desc = (DESC.search(fm).group(1).strip().strip('"') if DESC.search(fm) else "")
    body = text[m.end():] if m else text
    lines = len(body.splitlines())
    return name, desc, lines


def build(root: pathlib.Path) -> str:
    rows: dict[str, list[tuple[str, str, int]]] = {}
    for p in sorted(root.glob("*/*/SKILL.md")):
        if p.parent.parent.name.startswith("_"):
            continue  # _backlog stubs are unpublished and must not appear in the catalog
        cat = p.parent.parent.name
        rows.setdefault(cat, []).append(read(p))
    total = sum(len(v) for v in rows.values())
    out = [f"# Skill catalog\n\n{total} skills. Generated by `bin/catalog.py`; do not edit by hand.\n"]
    for cat in sorted(rows, key=lambda c: (list(GROUPS).index(c) if c in GROUPS else 99, c)):
        out.append(f"\n## {GROUPS.get(cat, cat)} ({len(rows[cat])})\n")
        for name, desc, lines in sorted(rows[cat]):
            out.append(f"- `{name}` - {desc} *({lines} lines)*")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parent.parent))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    root = pathlib.Path(args.root).expanduser().resolve()
    target = root / "CATALOG.md"
    text = build(root)
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print("CATALOG.md is stale; run bin/catalog.py")
            return 1
        print(f"catalog up to date ({text.count(chr(10) + '- ')} entries)")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} ({text.count(chr(10) + '- ')} skills)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
