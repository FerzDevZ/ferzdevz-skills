#!/usr/bin/env python3
"""Write CATALOG.md: skills grouped by their first tag, with section check."""
import collections, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "CATALOG.md"

def main() -> int:
    groups = collections.defaultdict(list)
    for p in sorted(ROOT.glob("*/SKILL.md")):
        text = p.read_text(errors="replace")
        meta = re.match(r"^---\n(.*?)\n---", text, re.S).group(1)
        desc = re.search(r"^description:\s*(.+)$", meta, re.M).group(1)
        tags = re.search(r"tags:\s*\[(.*?)\]", meta, re.M)
        raw = [x.strip() for x in tags.group(1).split(",")] if tags else []
        buckets = {
            "build": {"build", "compiler", "include", "encoding", "release", "git"},
            "data": {"database", "sql", "postgres", "mysql", "cache", "persistence"},
            "security": {"security", "anticheat", "ban", "exploit", "auth"},
            "ui": {"ui", "textdraw", "hud", "dialog", "ntd"},
            "world": {"mapping", "streamer", "object", "interior", "world", "lod"},
            "gameplay": {"gameplay", "job", "economy", "faction", "inventory",
                         "combat", "quest", "crafting", "vehicle", "survival"},
            "npc": {"npc", "actor"},
            "client": {"client", "android", "mobile"},
            "ops": {"ops", "deploy", "docker", "kubernetes", "monitoring", "backup",
                    "log", "metrics", "systemd"},
            "voice": {"voice", "audio"},
            "ci": {"ci", "testing", "test"},
            "meta": {"meta", "skills", "process", "navigation", "index"},
        }
        first = "other"
        for bucket, words in buckets.items():
            if any(t in words for t in raw):
                first = bucket
                break
        groups[first].append((p.parent.name, desc))
    lines = ["# SA-MP skill catalog", "", f"{sum(len(v) for v in groups.values())} skills. Generated by `build_catalog.py`; do not edit by hand.", ""]
    for g in sorted(groups):
        lines.append(f"## {g} ({len(groups[g])})")
        lines.append("")
        for name, desc in sorted(groups[g]):
            lines.append(f"- `{name}` - {desc}")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"catalog: {len(groups)} groups, {sum(len(v) for v in groups.values())} skills -> {OUT}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
